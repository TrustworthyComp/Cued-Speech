"""
MCCSD dataset class for FNA-SRA framework.

Feature layout on disk
----------------------
Hand features  (spatial stream):
    {hand_feat_root}/{signer}/{fileid}_left.npy   shape (T_L, 1024)
    {hand_feat_root}/{signer}/{fileid}_right.npy  shape (T_R, 1024)
    → pixel_value shape (T_L, 1024)   [only left hand used; see _load_hand_features]

Lip features  (spatiotemporal stream):
    {lip_feat_root}/{signer}/{fileid}.npy          shape (T_lip, 1024)
    → glor_value shape (T_lip, 1024)

Global features  (global stream, optional):
    {global_feat_root}/{signer}/{fileid}.npy       shape (T_all, 1024)
    → global_value shape (T_all, 1024)
    Extracted by scripts/vit_extract_global_feature.py
    (body-pose normalised upper-body crop, CLIP ViT-L/14 CLS token).

Annotation files
----------------
    {anno_root}/{mode}_info_ml.npy
    Generated by preprocess/MCCSD/make_info.py
"""

import torch
import os
import numpy as np
from typing import Dict, List, Optional, Any
from pathlib import Path


class MCCSD(torch.utils.data.Dataset):
    """
    Dataset class for the MCCSD (Multi-modal Chinese Cued Speech Dataset).

    Supports three feature streams compatible with the FNA-SRA FlanT5SLT model:
    - spatial        : left-hand ViT features        → pixel_value
    - spatiotemporal : lip ViT features              → glor_value
    - global         : full-frame ViT features       → global_value  (optional)
    """

    def __init__(
        self,
        anno_root: str,
        hand_feat_root: str,
        lip_feat_root: str,
        mode: str = 'train',
        spatial: bool = True,
        spatiotemporal: bool = True,
        hand_postfix_left: str = '_left',
        hand_postfix_right: str = '_right',
        lip_postfix: str = '',
        target: str = 'phoneme',
        global_feat_root: Optional[str] = None,
        global_postfix: str = '',
        lip_feat_dim: int = 1024,
    ):
        """
        Args:
            anno_root:          Directory containing {mode}_info_ml.npy
            hand_feat_root:     Root of hand feature files
                                (contains {signer}/ subdirs)
            lip_feat_root:      Root of lip feature files
                                (contains {signer}/ subdirs)
            mode:               'train', 'dev', or 'test'
            spatial:            Load hand features as pixel_value
            spatiotemporal:     Load lip features as glor_value
            hand_postfix_left:  Filename suffix for left-hand features
            hand_postfix_right: Filename suffix for right-hand features
            lip_postfix:        Filename suffix for lip features (usually '')
            target:             What the model should predict:
                                  'phoneme' – TextGrid phoneme sequence
                                             e.g. "n i h ao h en g ao"
                                  'gloss'   – Pinyin syllable sequence
                                             e.g. "ni hao hen gao"
                                  'text'    – Chinese sentence
                                             e.g. "你好，很高兴认识你。"
            global_feat_root:   Root of full-frame global ViT feature files
                                (contains {signer}/ subdirs).
                                If None, the global stream is disabled.
            global_postfix:     Filename suffix for global features (usually '').
        """
        super().__init__()

        self.anno_root          = Path(anno_root)
        self.hand_feat_root     = Path(hand_feat_root)
        self.lip_feat_root      = Path(lip_feat_root)
        self.mode               = mode
        self.spatial            = spatial
        self.spatiotemporal     = spatiotemporal
        self.hand_postfix_left  = hand_postfix_left
        self.hand_postfix_right = hand_postfix_right
        self.lip_postfix        = lip_postfix
        self.target             = target
        self.global_feat_root   = Path(global_feat_root) if global_feat_root else None
        self.global_postfix     = global_postfix
        self.use_global         = global_feat_root is not None
        self.lip_feat_dim       = lip_feat_dim

        if not (spatial or spatiotemporal):
            raise ValueError("At least one of 'spatial' or 'spatiotemporal' must be True")

        anno_path = self.anno_root / f'{mode}_info_ml.npy'
        if not anno_path.exists():
            raise FileNotFoundError(f'Annotation file not found: {anno_path}')

        raw = np.load(anno_path, allow_pickle=True).item()
        self.data = {int(k) if isinstance(k, (int, np.integer)) else k: v
                     for k, v in raw.items()
                     if isinstance(k, (int, np.integer))}
        self.num = len(self.data)

    # ------------------------------------------------------------------
    def _hand_feat_path(self, signer: str, fileid: str, side: str) -> Path:
        postfix = self.hand_postfix_left if side == 'left' else self.hand_postfix_right
        return self.hand_feat_root / signer / f'{fileid}{postfix}.npy'

    def _lip_feat_path(self, signer: str, fileid: str) -> Path:
        return self.lip_feat_root / signer / f'{fileid}{self.lip_postfix}.npy'

    def _global_feat_path(self, signer: str, fileid: str) -> Path:
        return self.global_feat_root / signer / f'{fileid}{self.global_postfix}.npy'

    # ------------------------------------------------------------------
    def _load_hand_features(self, signer: str, fileid: str) -> torch.Tensor:
        """
        Load hand features for the dominant cueing hand.

        In the extracted data, MediaPipe labels the primary cueing hand as
        'left' (camera-mirror convention: camera-left = signer's right hand).
        The '_right.npy' files contain only 1-5 frames and are MediaPipe
        mis-classifications, not genuine off-hand cues.  They are ignored.
        """
        p = self._hand_feat_path(signer, fileid, 'left')
        if p.exists():
            return torch.from_numpy(np.load(p))   # (T, 1024)
        print(f'[WARN] Missing hand feature: {p}')
        return torch.zeros(0, 1024)

    def _load_lip_features(self, signer: str, fileid: str) -> torch.Tensor:
        p = self._lip_feat_path(signer, fileid)
        if not p.exists():
            print(f'[WARN] Missing lip feature: {p}')
            return torch.zeros(0, self.lip_feat_dim)
        return torch.from_numpy(np.load(p))   # (T_lip, D)

    def _load_global_features(self, signer: str, fileid: str) -> torch.Tensor:
        """Load body-pose-normalised upper-body ViT features (all video frames)."""
        p = self._global_feat_path(signer, fileid)
        if not p.exists():
            print(f'[WARN] Missing global feature: {p}')
            return torch.zeros(0, 1024)
        return torch.from_numpy(np.load(p))   # (T_all, 1024)

    # ------------------------------------------------------------------
    def __getitem__(self, index: int) -> Dict[str, Any]:
        entry   = self.data[index]
        fileid  = entry['fileid']
        signer  = entry['signer']

        pixel_value  = None
        glor_value   = None
        global_value = None

        if self.spatial:
            pixel_value = self._load_hand_features(signer, fileid)

        if self.spatiotemporal:
            glor_value = self._load_lip_features(signer, fileid)

        if self.use_global:
            global_value = self._load_global_features(signer, fileid)

        # Build the prediction target string based on self.target
        if self.target == 'phoneme':
            # Space-separated phoneme labels from TextGrid phoneme_intervals.
            # Each element is [t_start, t_end, label]; we keep the labels only.
            intervals = entry.get('phoneme_intervals', [])
            text = ' '.join(iv[2] for iv in intervals if iv[2])
            if not text:          # fallback: use gloss if intervals empty
                text = entry.get('gloss', '')
        elif self.target == 'gloss':
            text = entry.get('gloss', '').strip()
        else:                     # 'text' – Chinese sentence (original behaviour)
            text = entry.get('text', '').strip()
            if text and not text.endswith('。') and not text.endswith('.'):
                text = text + '。'

        return {
            'pixel_value':    pixel_value,
            'glor_value':     glor_value,
            'global_value':   global_value,
            'bool_mask_pos':  None,
            'text':           text,
            'gloss':          entry.get('gloss', ''),
            'id':             fileid,
            'signer':         signer,
            'num_frames':     len(pixel_value) if pixel_value is not None else 0,
            'global_frames':  len(global_value) if global_value is not None else 0,
            'lang':           entry.get('lang', 'Chinese'),
            # Multilingual fields required by t5_sra.py when use_in_context=True
            # (set equal to Chinese text; disable in config via use_in_context: false)
            'en_text':        entry.get('en_text', text),
            'es_text':        entry.get('es_text', text),
            'fr_text':        entry.get('fr_text', text),
            'original_info':  entry,
        }

    def __len__(self) -> int:
        return self.num

    @staticmethod
    def collate_fn(batch: List[Dict]) -> List[Dict]:
        return batch
